#!/usr/bin/env python3
# -*- coding: utf-8 -*-
#
#   One-time generator for the PHOIBLE coverage-test fixture
#
#   Writes cv-patterns/tests/fixtures/phonemes2cv/phoible_segments.txt: the
#   segment column of PHOIBLE's own segment feature table, one per line. Used
#   offline by test_phonemes2cv_source.py to check that no PHOIBLE segment
#   makes phonemes2cv.Convert() emit an unrecognised "?" -- see
#   cv-patterns/SPEC.md. PHOIBLE is the independent net for this converter:
#   it is not the source BIPA is (see cv-patterns/SPEC.md's "Why BIPA is the
#   source, and what PHOIBLE is for"), so this fixture is never regenerated by
#   promoting Convert()'s own output.
#
#   Run once by hand if PHOIBLE's segment inventory needs re-checking against
#   a newer commit; not part of the pytest suite itself, and not a converter
#   -- see AGENTS.md's Converter Conventions.
#
#   Tim Kempton
#   September 2026
#
#   Platforms: any Python 3
#

import csv
import io
import urllib.request
from pathlib import Path

# Pinned by commit rather than a tag, since phoible/dev has none -- re-derive
# this fixture (and update the commit named in cv-patterns/SPEC.md) if
# PHOIBLE's segment inventory needs rechecking.
PHOIBLE_COMMIT = "fd7894c10e6f894ac37f3e22765d15504b8eb25d"
URL = (
    f"https://raw.githubusercontent.com/phoible/dev/{PHOIBLE_COMMIT}"
    "/raw-data/FEATURES/phoible-segments-features.tsv"
)
EXPECTED_ROW_COUNT = 2162

OUTPUT_PATH = (
    Path(__file__).resolve().parent.parent
    / "tests" / "fixtures" / "phonemes2cv" / "phoible_segments.txt"
)


def main():
    with urllib.request.urlopen(URL) as response:
        text = response.read().decode("utf-8")
    rows = list(csv.DictReader(io.StringIO(text), delimiter="\t"))
    assert len(rows) == EXPECTED_ROW_COUNT, (
        f"expected {EXPECTED_ROW_COUNT} PHOIBLE segments, got {len(rows)} -- "
        "PHOIBLE has changed; re-check cv-patterns/SPEC.md's coverage claim"
    )
    segments = sorted({row["segment"] for row in rows})
    OUTPUT_PATH.write_text("\n".join(segments) + "\n", encoding="utf-8")
    print(f"Wrote {len(segments)} distinct segments to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
